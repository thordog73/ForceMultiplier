'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const s=fs.readFileSync('dist/index.html','utf8');
assert(s.includes('force-multiplier-visual-sim-v2'));
assert(s.includes('5 functions · 20 levels each · visual simulations'));
assert(!s.includes('4-HOUR GRADUATE'));
assert(!s.includes('24-HOUR EXPERT'));
for(const term of ['6-turn-4','Add the spare','12-turn-10','Build the weekly checkerboard','Combine compatible work','Plan a modification','Repair a disrupted schedule','Review execution and improve','Did the action work?','Find the controlling requirement','Stop the error from recurring','Verify incident closure'])assert(s.includes(term),`missing ${term}`);
assert(s.includes('./worlds.html'));
assert(s.includes('./native.js'));
const ids=[...s.matchAll(/\['([SADIB]\d{2})','/g)].map(m=>m[1]);
for(const prefix of ['S','A','D','I','B'])for(let i=1;i<=20;i++)assert(ids.includes(prefix+String(i).padStart(2,'0')),'missing '+prefix+i);
const scenarioCount=(s.match(/\['[^']+','[^']+',\[['SADIB]/g)||[]).length;
assert.equal(scenarioCount,100,'visual redesign must expose exactly 100 playable levels');
for(const role of ['scheduling','analysis','documentation','integrity','systems'])assert(s.includes(`const CHAPTERS`)&&s.includes(role+':['));
assert(s.includes('function unlockedLevel'));
assert(s.includes('Complete one level to unlock the next'));
assert(s.includes('Execute simulation'));
assert(s.includes('function runOutcome'));
assert(s.includes('function validateScheduleBoard'));
assert(s.includes('class="board"'));
assert(s.includes('trendSvg'));
assert(s.includes('Evidence A'));
assert(s.includes('System logs'));
console.log('PASS 20-level visual game: 100 playable levels, sequential unlocks, replayable variations, scheduling execution animation, and all five visual work-product engines.');

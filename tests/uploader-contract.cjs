'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const ps=fs.readFileSync('scripts/Upload.ps1','utf8');
const cmd=fs.readFileSync('UPLOAD.cmd','utf8');
const cm=fs.readFileSync('codemagic.yaml','utf8');
assert(ps.includes("$WorkflowId = 'ios-release'"),'Uploader must target ios-release');
assert(ps.includes('22.8.1'),'Uploader must identify the 22.8.1 release candidate');
assert(ps.includes("https://api.codemagic.io/builds"),'Uploader must start Codemagic via REST API');
assert(ps.includes("'x-auth-token' = $Token"),'Uploader must authenticate with x-auth-token');
assert(ps.includes("https://api.codemagic.io/apps"),'Uploader must discover Codemagic app ID');
assert(!ps.includes('$matches = @()'),'Uploader must not reuse PowerShell automatic $Matches variable');
assert(ps.includes('$matchedApps = @()'),'Uploader must use a dedicated Codemagic app match list');
assert(ps.includes('ConvertFrom-SecureString'),'Token must be stored encrypted for the Windows user');
assert(ps.includes('ConvertTo-SecureString'),'Saved token must be decrypted through Windows user context');
assert(ps.includes("workflowId = $WorkflowId"),'Build request must include workflow id');
assert(ps.includes("branch = $Branch"),'Build request must include pushed branch');
assert(!ps.includes('webhook'),'Direct uploader must not depend on a webhook');
assert(cmd.includes('scripts\\Upload.ps1'),'UPLOAD.cmd must invoke the direct uploader');
assert(cm.includes('ios-release:'),'Codemagic yaml must contain ios-release');
assert(cm.includes('app_store_connect: ten-minute-wins-apple'),'Known App Store Connect integration must be retained');
assert(cm.includes('APP_STORE_APPLE_ID: "6833361372"'),'App Store Connect app ID must be explicit');
assert(cm.includes('submit_to_testflight: true'),'TestFlight submission must be enabled');
assert(cm.includes('submit_to_app_store: false'),'Public App Store review must remain disabled');
assert(cm.includes('npm run ios:prepare && npm run ios:verify'),'Codemagic must verify generated iOS assets after preparation');
console.log('PASS uploader contract: direct Codemagic API trigger, encrypted one-time token, app discovery, ios-release, TestFlight upload path.');
